"""Builds the ARK animation for the UNO Q's 13x8 LED matrix (brightness 0-7).

Writes frames.h for the sketch, and with --preview a GIF to look at.

Story: waves; the word ARK pops up out of them, then sinks back; the ark rises
out of it and rides the waves through rain while its windows light up one
by one (people coming aboard); the rain stops and a dove crosses.
"""
import sys

W, H = 13, 8

# The ark, top row first. Digits are brightness; '.' is off.
# Mast with a crossbar, roof, a cabin with three windows, deck, hull.
ARK = [
    "......6......",
    ".....666.....",
    "......6......",
    "...4444444...",
    "...3w3w3w3...",
    ".77777777777.",
    "..666666666..",
]
WINDOWS = [(4, 4), (4, 6), (4, 8)]

GLYPHS = {
    "A": [".#.", "#.#", "###", "#.#", "#.#"],
    "R": ["##.", "#.#", "##.", "#.#", "#.#"],
    "K": ["#.#", "#.#", "##.", "#.#", "#.#"],
}

WAVE = [7, 4, 1, 4]       # bottom row, scrolls one step per frame
SWELL = [0, 2, 0, 0]      # faint second row at the sides


def blank():
    return [[0] * W for _ in range(H)]


def waves(f, t):
    for x in range(W):
        f[7][x] = max(f[7][x], WAVE[(x + t) % 4])
        if f[6][x] == 0:
            f[6][x] = SWELL[(x + t + 2) % 4]


def put(f, x, y, v):
    if 0 <= x < W and 0 <= y < H:
        f[y][x] = max(f[y][x], v)


def ark(f, dy, lit):
    for r, row in enumerate(ARK):
        for x, ch in enumerate(row):
            y = r + dy
            if not (0 <= y < H):
                continue
            if ch == "w":
                i = [wx for (_, wx) in WINDOWS].index(x)
                f[y][x] = lit[i]
            elif ch != ".":
                # The hull covers the water it sits in.
                f[y][x] = int(ch)


def word(f, dy, level):
    x0 = 1
    for ch in "ARK":
        for r, row in enumerate(GLYPHS[ch]):
            for c, p in enumerate(row):
                if p == "#":
                    put(f, x0 + c, 1 + r + dy, level)
        x0 += 4


RAIN_COLS = [0, 3, 11, 12, 1, 10]


def rain(f, t):
    for i, x in enumerate(RAIN_COLS):
        y = (t + i * 3) % 6
        if f[y][x] == 0:
            f[y][x] = 2


def build():
    frames = []  # (pixels, ms)
    t = 0

    def add(f, ms):
        nonlocal t
        frames.append((f, ms))
        t += 1

    for _ in range(6):
        f = blank(); waves(f, t); add(f, 140)
    # Pops up out of the water with a one-row overshoot, then settles.
    for dy in [6, 4, 2, 0, -1, 0]:
        f = blank(); word(f, dy, 7); waves(f, t); add(f, 70)
    for _ in range(12):
        f = blank(); word(f, 0, 7); waves(f, t); add(f, 140)
    for dy in range(1, 7):
        f = blank(); word(f, dy, 7); waves(f, t); add(f, 110)
    for dy in range(7, -1, -1):
        f = blank(); ark(f, dy, [0, 0, 0]); waves(f, t); add(f, 120)

    bob = [0, 0, 0, 1, 1, 1]
    for i in range(48):
        lit = [min(7, max(0, (i - 10 * k) // 2)) for k in range(3)]
        f = blank(); rain(f, i); ark(f, bob[i % 6], lit); waves(f, t); add(f, 140)
    for i in range(16):
        f = blank(); ark(f, bob[i % 6], [7, 7, 7]); waves(f, t)
        x = i - 2
        put(f, x, 0, 7)                    # dove
        put(f, x - 1, (i % 2), 4)          # wing beat
        add(f, 120)
    for i in range(6):
        f = blank(); ark(f, bob[i % 6], [7, 7, 7]); waves(f, t); add(f, 140)
    return frames


def header(frames):
    out = ["// Generated by frames.py. Do not edit by hand.", "#pragma once", "",
           f"const int FRAME_COUNT = {len(frames)};",
           "const uint8_t FRAMES[][104] = {"]
    for f, _ in frames:
        flat = [v for row in f for v in row]
        out.append("  {" + ",".join(map(str, flat)) + "},")
    out.append("};")
    out.append("const uint16_t FRAME_MS[] = {" + ",".join(str(ms) for _, ms in frames) + "};")
    return "\n".join(out) + "\n"


def preview(frames, path):
    # 13x8 dots scaled up, blue like the board's LEDs, as PPM frames.
    import os, subprocess, tempfile
    d = tempfile.mkdtemp()
    S, G = 24, 4
    names = []
    for n, (f, ms) in enumerate(frames):
        w, h = W * S, H * S
        px = bytearray(b"\x0a\x0c\x14" * (w * h))
        for y in range(H):
            for x in range(W):
                v = f[y][x]
                col = (int(20 + 15 * v), int(40 + 25 * v), int(70 + 26 * v)) if v else (22, 26, 38)
                for yy in range(y * S + G, y * S + S - G):
                    for xx in range(x * S + G, x * S + S - G):
                        i = (yy * w + xx) * 3
                        px[i:i + 3] = bytes(col)
        name = os.path.join(d, f"{n:03d}.ppm")
        with open(name, "wb") as fh:
            fh.write(f"P6 {w} {h} 255\n".encode() + px)
        names += ["-delay", str(ms // 10), name]
    subprocess.run(["magick", *names, "-loop", "0", path], check=True)


if __name__ == "__main__":
    frames = build()
    here = __file__.rsplit("/", 1)[0]
    with open(f"{here}/sketch/frames.h", "w") as fh:
        fh.write(header(frames))
    if "--preview" in sys.argv:
        preview(frames, sys.argv[-1])
    print(len(frames), "frames,", sum(ms for _, ms in frames) / 1000, "s")
